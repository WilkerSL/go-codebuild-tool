const Header = "// Code generated by codebuild. DO NOT EDIT."

func jsonName(name string) string {
	var b strings.Builder
	upper := false
	for _, r := range name {
		if r == '_' {
			upper = true
			continue
		}
		if upper && r >= 'a' && r <= 'z' {
			r -= 'a' - 'A'
		}
		upper = false
		b.WriteRune(r)
	}
	return b.String()
}

func (f *File) usedImports() []string {
	used := map[string]bool{}
	for _, msg := range f.Messages {
		for _, fd := range msg.Fields {
			switch {
			case fd.TypeName == Timestamp:
				used[timestampPath] = true
			case strings.HasPrefix(fd.TypeName, "."+CommonPackage+".") && f.Package != CommonPackage:
				used[commonPath] = true
			}
		}
	}
	for _, svc := range f.Services {
		for _, m := range svc.Methods {
			for _, t := range []string{m.Input, m.Output} {
				switch {
				case t == Empty:
					used[emptyPath] = true
				case strings.HasPrefix(t, "."+CommonPackage+"."):
					used[commonPath] = true
				}
			}
		}
	}
	var out []string
	for p := range used {
		out = append(out, p)
	}
	return sortedImports(out)
}

func (f *File) descriptor() *descriptorpb.FileDescriptorProto {
	fd := &descriptorpb.FileDescriptorProto{
		Name:       proto.String(f.Path),
		Package:    proto.String(f.Package),
		Syntax:     proto.String("proto3"),
		Dependency: f.usedImports(),
		Options:    &descriptorpb.FileOptions{GoPackage: proto.String(f.GoImport + ";" + f.GoName)},
	}
	for _, msg := range f.Messages {
		dp := &descriptorpb.DescriptorProto{Name: proto.String(msg.Name)}
		for _, fld := range msg.Fields {
			label := descriptorpb.FieldDescriptorProto_LABEL_OPTIONAL
			if fld.Repeated {
				label = descriptorpb.FieldDescriptorProto_LABEL_REPEATED
			}
			field := &descriptorpb.FieldDescriptorProto{
				Name:     proto.String(fld.Name),
				Number:   proto.Int32(fld.Number),
				Label:    label.Enum(),
				Type:     fld.Type.Enum(),
				JsonName: proto.String(jsonName(fld.Name)),
			}
			if fld.TypeName != "" {
				field.TypeName = proto.String(fld.TypeName)
			}
			if fld.Optional {
				field.Proto3Optional = proto.Bool(true)
				field.OneofIndex = proto.Int32(int32(len(dp.OneofDecl)))
				dp.OneofDecl = append(dp.OneofDecl, &descriptorpb.OneofDescriptorProto{Name: proto.String("_" + fld.Name)})
			}
			dp.Field = append(dp.Field, field)
		}
		for _, n := range msg.Reserved {
			dp.ReservedRange = append(dp.ReservedRange, &descriptorpb.DescriptorProto_ReservedRange{Start: proto.Int32(n), End: proto.Int32(n + 1)})
		}
		fd.MessageType = append(fd.MessageType, dp)
	}
	for _, svc := range f.Services {
		sd := &descriptorpb.ServiceDescriptorProto{Name: proto.String(svc.Name)}
		for _, m := range svc.Methods {
			sd.Method = append(sd.Method, &descriptorpb.MethodDescriptorProto{
				Name:       proto.String(m.Name),
				InputType:  proto.String(m.Input),
				OutputType: proto.String(m.Output),
			})
		}
		fd.Service = append(fd.Service, sd)
	}
	return fd
}

func (f *File) typeName(full string) string {
	if prefix := "." + f.Package + "."; strings.HasPrefix(full, prefix) {
		return strings.TrimPrefix(full, prefix)
	}
	return strings.TrimPrefix(full, ".")
}

func scalarName(t FieldType) string {
	switch t {
	case TypeBool:
		return "bool"
	case TypeInt32:
		return "int32"
	case TypeInt64:
		return "int64"
	case TypeFloat:
		return "float"
	case TypeDouble:
		return "double"
	case TypeBytes:
		return "bytes"
	}
	return "string"
}

func (f *File) Proto() []byte {
	var b bytes.Buffer
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	w("%s\n\nsyntax = \"proto3\";\n\npackage %s;\n", Header, f.Package)
	if imports := f.usedImports(); len(imports) > 0 {
		w("\n")
		for _, imp := range imports {
			w("import %q;\n", imp)
		}
	}
	w("\noption go_package = %q;\n", f.GoImport+";"+f.GoName)
	for _, msg := range f.Messages {
		w("\nmessage %s {\n", msg.Name)
		for _, fld := range msg.Fields {
			t := scalarName(fld.Type)
			if fld.Type == TypeMessage {
				t = f.typeName(fld.TypeName)
			}
			label := ""
			switch {
			case fld.Repeated:
				label = "repeated "
			case fld.Optional:
				label = "optional "
			}
			w("  %s%s %s = %d;\n", label, t, fld.Name, fld.Number)
		}
		if len(msg.Reserved) > 0 {
			numbers := make([]string, len(msg.Reserved))
			for i, n := range msg.Reserved {
				numbers[i] = strconv.Itoa(int(n))
			}
			w("  reserved %s;\n", strings.Join(numbers, ", "))
		}
		w("}\n")
	}
	for _, svc := range f.Services {
		w("\nservice %s {\n", svc.Name)
		for _, m := range svc.Methods {
			w("  rpc %s(%s) returns (%s);\n", m.Name, f.typeName(m.Input), f.typeName(m.Output))
		}
		w("}\n")
	}
	return b.Bytes()
}

type Output struct {
	Path    string
	Content []byte
}

func (s *Set) Generate() ([]Output, error) {
	req := &pluginpb.CodeGeneratorRequest{
		ProtoFile: []*descriptorpb.FileDescriptorProto{
			protodesc.ToFileDescriptorProto(timestamppb.File_google_protobuf_timestamp_proto),
			protodesc.ToFileDescriptorProto(emptypb.File_google_protobuf_empty_proto),
		},
		Parameter: proto.String("paths=source_relative"),
	}
	for _, f := range s.All() {
		req.FileToGenerate = append(req.FileToGenerate, f.Path)
		req.ProtoFile = append(req.ProtoFile, f.descriptor())
	}
	plugin, err := protogen.Options{}.New(req)
	if err != nil {
		return nil, fmt.Errorf("contracts: %w", err)
	}
	byPath := map[string]*File{}
	for _, f := range s.All() {
		byPath[f.Path] = f
	}
	for _, pf := range plugin.Files {
		if !pf.Generate {
			continue
		}
		gengo.GenerateFile(plugin, pf)
		generateGRPC(plugin, pf)
		if f := byPath[pf.Desc.Path()]; f != nil {
			for _, pm := range pf.Messages {
				msg := f.Message(string(pm.Desc.Name()))
				for _, pfld := range pm.Fields {
					if fld := msg.Field(string(pfld.Desc.Name())); fld != nil {
						fld.GoName = pfld.GoName
					}
				}
			}
		}
	}
	resp := plugin.Response()
	if resp.Error != nil {
		return nil, fmt.Errorf("contracts: %s", resp.GetError())
	}
	var out []Output
	for _, f := range s.All() {
		out = append(out, Output{Path: f.Path, Content: f.Proto()})
	}
	for _, rf := range resp.File {
		content, err := stripComments(rf.GetName(), []byte(rf.GetContent()))
		if err != nil {
			return nil, err
		}
		out = append(out, Output{Path: rf.GetName(), Content: content})
	}
	slices.SortFunc(out, func(a, b Output) int { return strings.Compare(a.Path, b.Path) })
	return out, nil
}

func stripComments(name string, src []byte) ([]byte, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, name, src, parser.SkipObjectResolution)
	if err != nil {
		return nil, fmt.Errorf("contracts: parse %s: %w", name, err)
	}
	var b bytes.Buffer
	b.WriteString(Header + "\n\n")
	if err := format.Node(&b, fset, file); err != nil {
		return nil, fmt.Errorf("contracts: format %s: %w", name, err)
	}
	return format.Source(b.Bytes())
}

const (
	contextPackage = protogen.GoImportPath("context")
	grpcPackage    = protogen.GoImportPath("google.golang.org/grpc")
	codesPackage   = protogen.GoImportPath("google.golang.org/grpc/codes")
	statusPackage  = protogen.GoImportPath("google.golang.org/grpc/status")
)

func generateGRPC(plugin *protogen.Plugin, file *protogen.File) {
	if len(file.Services) == 0 {
		return
	}
	g := plugin.NewGeneratedFile(file.GeneratedFilenamePrefix+"_grpc.pb.go", file.GoImportPath)
	g.P("package ", file.GoPackageName)
	g.P()
	g.P("const _ = ", grpcPackage.Ident("SupportPackageIsVersion9"))
	ctx := contextPackage.Ident("Context")
	for _, svc := range file.Services {
		name := svc.GoName
		client := name + "Client"
		server := name + "Server"
		impl := strings.ToLower(client[:1]) + client[1:]
		unimplemented := "Unimplemented" + server
		g.P()
		g.P("const (")
		for _, m := range svc.Methods {
			g.P(name, "_", m.GoName, "_FullMethodName = ", strconv.Quote("/"+string(svc.Desc.FullName())+"/"+string(m.Desc.Name())))
		}
		g.P(")")
		g.P()
		g.P("type ", client, " interface {")
		for _, m := range svc.Methods {
			g.P(m.GoName, "(ctx ", ctx, ", in *", m.Input.GoIdent, ", opts ...", grpcPackage.Ident("CallOption"), ") (*", m.Output.GoIdent, ", error)")
		}
		g.P("}")
		g.P()
		g.P("type ", impl, " struct {")
		g.P("cc ", grpcPackage.Ident("ClientConnInterface"))
		g.P("}")
		g.P()
		g.P("func New", client, "(cc ", grpcPackage.Ident("ClientConnInterface"), ") ", client, " {")
		g.P("return &", impl, "{cc}")
		g.P("}")
		for _, m := range svc.Methods {
			g.P()
			g.P("func (c *", impl, ") ", m.GoName, "(ctx ", ctx, ", in *", m.Input.GoIdent, ", opts ...", grpcPackage.Ident("CallOption"), ") (*", m.Output.GoIdent, ", error) {")
			g.P("cOpts := append([]", grpcPackage.Ident("CallOption"), "{", grpcPackage.Ident("StaticMethod"), "()}, opts...)")
			g.P("out := new(", m.Output.GoIdent, ")")
			g.P("if err := c.cc.Invoke(ctx, ", name, "_", m.GoName, "_FullMethodName, in, out, cOpts...); err != nil {")
			g.P("return nil, err")
			g.P("}")
			g.P("return out, nil")
			g.P("}")
		}
		g.P()
		g.P("type ", server, " interface {")
		for _, m := range svc.Methods {
			g.P(m.GoName, "(", ctx, ", *", m.Input.GoIdent, ") (*", m.Output.GoIdent, ", error)")
		}
		g.P("mustEmbed", unimplemented, "()")
		g.P("}")
		g.P()
		g.P("type ", unimplemented, " struct{}")
		for _, m := range svc.Methods {
			g.P()
			g.P("func (", unimplemented, ") ", m.GoName, "(", ctx, ", *", m.Input.GoIdent, ") (*", m.Output.GoIdent, ", error) {")
			g.P("return nil, ", statusPackage.Ident("Error"), "(", codesPackage.Ident("Unimplemented"), ", ", strconv.Quote("method "+m.GoName+" not implemented"), ")")
			g.P("}")
		}
		g.P()
		g.P("func (", unimplemented, ") mustEmbed", unimplemented, "() {}")
		g.P()
		g.P("func Register", server, "(s ", grpcPackage.Ident("ServiceRegistrar"), ", srv ", server, ") {")
		g.P("s.RegisterService(&", name, "_ServiceDesc, srv)")
		g.P("}")
		for _, m := range svc.Methods {
			handler := "_" + name + "_" + m.GoName + "_Handler"
			g.P()
			g.P("func ", handler, "(srv any, ctx ", ctx, ", dec func(any) error, interceptor ", grpcPackage.Ident("UnaryServerInterceptor"), ") (any, error) {")
			g.P("in := new(", m.Input.GoIdent, ")")
			g.P("if err := dec(in); err != nil {")
			g.P("return nil, err")
			g.P("}")
			g.P("if interceptor == nil {")
			g.P("return srv.(", server, ").", m.GoName, "(ctx, in)")
			g.P("}")
			g.P("info := &", grpcPackage.Ident("UnaryServerInfo"), "{Server: srv, FullMethod: ", name, "_", m.GoName, "_FullMethodName}")
			g.P("handler := func(ctx ", ctx, ", req any) (any, error) {")
			g.P("return srv.(", server, ").", m.GoName, "(ctx, req.(*", m.Input.GoIdent, "))")
			g.P("}")
			g.P("return interceptor(ctx, in, info, handler)")
			g.P("}")
		}
		g.P()
		g.P("var ", name, "_ServiceDesc = ", grpcPackage.Ident("ServiceDesc"), "{")
		g.P("ServiceName: ", strconv.Quote(string(svc.Desc.FullName())), ",")
		g.P("HandlerType: (*", server, ")(nil),")
		g.P("Methods: []", grpcPackage.Ident("MethodDesc"), "{")
		for _, m := range svc.Methods {
			g.P("{MethodName: ", strconv.Quote(string(m.Desc.Name())), ", Handler: _", name, "_", m.GoName, "_Handler},")
		}
		g.P("},")
		g.P("Streams: []", grpcPackage.Ident("StreamDesc"), "{},")
		g.P("Metadata: ", strconv.Quote(path.Clean(file.Desc.Path())), ",")
		g.P("}")
	}
}
