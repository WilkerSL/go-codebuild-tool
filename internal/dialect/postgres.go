package dialect

import (
	"strconv"
	"strings"

	"github.com/WilkerSL/go-codebuild-tool/internal/schema"
)

type Postgres struct{}

func (Postgres) Name() string { return "postgres" }

func (Postgres) Driver() Driver {
	return Driver{
		Module:     "github.com/jackc/pgx/v5",
		Version:    "v5.11.0",
		Import:     "github.com/jackc/pgx/v5/stdlib",
		Name:       "pgx",
		ExampleDSN: "postgres://app:app@localhost:5432/app?sslmode=disable",
	}
}

func (Postgres) Quote(ident string) string {
	return `"` + strings.ReplaceAll(ident, `"`, `""`) + `"`
}

func (Postgres) Placeholder(n int) string { return "$" + strconv.Itoa(n) }

func (Postgres) Positional() bool { return false }

func (Postgres) FilterParam(placeholder string, kind schema.ColumnKind) string {
	return placeholder + "::" + postgresCastType(kind)
}

func postgresCastType(kind schema.ColumnKind) string {
	switch kind {
	case schema.ColumnUUID:
		return "uuid"
	case schema.ColumnBool:
		return "boolean"
	case schema.ColumnInt16:
		return "smallint"
	case schema.ColumnInt32:
		return "integer"
	case schema.ColumnInt64:
		return "bigint"
	}
	return "text"
}

func (Postgres) ColumnType(c *schema.Column) string {
	switch c.Kind {
	case schema.ColumnString:
		if c.Size > 0 {
			return "VARCHAR(" + strconv.Itoa(c.Size) + ")"
		}
		return "TEXT"
	case schema.ColumnBool:
		return "BOOLEAN"
	case schema.ColumnInt16:
		return "SMALLINT"
	case schema.ColumnInt32:
		return "INTEGER"
	case schema.ColumnInt64:
		return "BIGINT"
	case schema.ColumnFloat32:
		return "REAL"
	case schema.ColumnFloat64:
		return "DOUBLE PRECISION"
	case schema.ColumnBytes:
		return "BYTEA"
	case schema.ColumnTime:
		return "TIMESTAMPTZ"
	case schema.ColumnUUID:
		return "UUID"
	}
	return "TEXT"
}

func (Postgres) Now() string { return "now()" }

func (Postgres) Strategy() InsertStrategy { return ReturnRow }

func (d Postgres) InsertSQL(table string, columns, values []string, returning []Returned) string {
	return "INSERT INTO " + d.Quote(table) + " (\n" + indent(columns) + "\n) VALUES (\n" + indent(values) + "\n)\nRETURNING\n" + indent(returnedColumns(returning))
}

func (d Postgres) UpdateSQL(table string, sets []string, where string, returning []Returned) string {
	return "UPDATE " + d.Quote(table) + "\nSET\n" + indent(sets) + "\nWHERE " + where + "\nRETURNING\n" + indent(returnedColumns(returning))
}

func (Postgres) Paginate(param func(ArgKind) string) string {
	limit := param(ArgLimit)
	return "LIMIT " + limit + " OFFSET " + param(ArgOffset)
}

func (Postgres) QueryHint() string { return "" }

func (d Postgres) LinkSQL(table string, columns, params [2]string) string {
	return "INSERT INTO " + d.Quote(table) + " (" + d.Quote(columns[0]) + ", " + d.Quote(columns[1]) + ")\nVALUES (" + params[0] + ", " + params[1] + ")\nON CONFLICT DO NOTHING"
}

func (Postgres) ScanTimeAdapter() bool { return false }

func (Postgres) RecreateDependents() bool { return false }

func (Postgres) Limits() Limits {
	return Limits{PartialIndexes: true}
}

func (d Postgres) Migration(changes []schema.Change, before, after *schema.Database) string {
	return renderMigration(d, changes, before, after)
}

func (d Postgres) literal(c *schema.Column) string {
	if c.Default.Kind == schema.DefaultNow {
		return "now()"
	}
	return literal(c, c.Default.Value, "", "TRUE", "FALSE")
}

func (d Postgres) columnDef(c *schema.Column) string {
	def := d.Quote(c.Name) + " " + d.ColumnType(c)
	if !c.Nullable {
		def += " NOT NULL"
	}
	if c.Identity {
		def += " GENERATED BY DEFAULT AS IDENTITY"
	}
	if c.Default != nil {
		def += " DEFAULT " + d.literal(c)
	}
	return def
}

func (d Postgres) fkDef(fk *schema.ForeignKey) string {
	return "CONSTRAINT " + d.Quote(fk.Name) + " FOREIGN KEY (" + strings.Join(quoteAll(d, fk.Columns), ", ") + ") REFERENCES " +
		d.Quote(fk.RefTable) + " (" + strings.Join(quoteAll(d, fk.RefColumns), ", ") + ") ON DELETE " + fkActionDefault(fk.OnDelete)
}

func (d Postgres) createTable(_ renderContext, c schema.Change) []string {
	t := c.Table
	var lines []string
	for _, col := range t.Columns {
		lines = append(lines, d.columnDef(col))
	}
	if t.PrimaryKey != nil {
		lines = append(lines, "CONSTRAINT "+d.Quote(t.PrimaryKey.Name)+" PRIMARY KEY ("+strings.Join(quoteAll(d, t.PrimaryKey.Columns), ", ")+")")
	}
	for _, fk := range c.InlineFKs {
		lines = append(lines, d.fkDef(fk))
	}
	for _, ck := range t.Checks {
		lines = append(lines, "CONSTRAINT "+d.Quote(ck.Name)+" CHECK ("+checkExpression(d, ck, "")+")")
	}
	return []string{"CREATE TABLE " + d.Quote(t.Name) + " (\n" + indent(lines) + "\n)"}
}

func (d Postgres) dropTable(_ renderContext, c schema.Change) []string {
	return []string{"DROP TABLE " + d.Quote(c.TableName)}
}

func (d Postgres) addColumn(_ renderContext, table string, col *schema.Column) []string {
	return []string{"ALTER TABLE " + d.Quote(table) + " ADD COLUMN " + d.columnDef(col)}
}

func (d Postgres) dropColumn(_ renderContext, table string, col *schema.Column) []string {
	return []string{"ALTER TABLE " + d.Quote(table) + " DROP COLUMN " + d.Quote(col.Name)}
}

func (d Postgres) alterColumn(_ renderContext, table string, old, new *schema.Column) []string {
	var actions []string
	name := d.Quote(new.Name)
	if !columnsEqualType(old, new) {
		action := "ALTER COLUMN " + name + " TYPE " + d.ColumnType(new)
		if old.Kind != new.Kind {
			action += " USING " + name + "::" + d.ColumnType(new)
		}
		actions = append(actions, action)
	}
	if old.Nullable != new.Nullable {
		if new.Nullable {
			actions = append(actions, "ALTER COLUMN "+name+" DROP NOT NULL")
		} else {
			actions = append(actions, "ALTER COLUMN "+name+" SET NOT NULL")
		}
	}
	if !defaultsEqual(old, new) {
		if new.Default == nil {
			actions = append(actions, "ALTER COLUMN "+name+" DROP DEFAULT")
		} else {
			actions = append(actions, "ALTER COLUMN "+name+" SET DEFAULT "+d.literal(new))
		}
	}
	if len(actions) == 0 {
		return nil
	}
	return []string{"ALTER TABLE " + d.Quote(table) + "\n" + indent(actions)}
}

func (d Postgres) createIndex(_ renderContext, table string, idx *schema.Index, _ bool) []string {
	stmt := "CREATE "
	if idx.Unique {
		stmt += "UNIQUE "
	}
	stmt += "INDEX " + d.Quote(idx.Name) + " ON " + d.Quote(table) + " (" + strings.Join(quoteAll(d, idx.Columns), ", ") + ")"
	if idx.NotDeleted {
		stmt += " WHERE " + d.Quote(schema.DeletedAtColumn) + " IS NULL"
	}
	return []string{stmt}
}

func (d Postgres) dropIndex(_ renderContext, _ string, idx *schema.Index, _ bool) []string {
	return []string{"DROP INDEX " + d.Quote(idx.Name)}
}

func (d Postgres) addForeignKey(_ renderContext, table string, fk *schema.ForeignKey) []string {
	return []string{"ALTER TABLE " + d.Quote(table) + " ADD " + d.fkDef(fk)}
}

func (d Postgres) dropForeignKey(_ renderContext, table string, fk *schema.ForeignKey) []string {
	return []string{"ALTER TABLE " + d.Quote(table) + " DROP CONSTRAINT " + d.Quote(fk.Name)}
}

func (d Postgres) addCheck(_ renderContext, table string, ck *schema.Check) []string {
	return []string{"ALTER TABLE " + d.Quote(table) + " ADD CONSTRAINT " + d.Quote(ck.Name) + " CHECK (" + checkExpression(d, ck, "") + ")"}
}

func (d Postgres) dropCheck(_ renderContext, table string, ck *schema.Check) []string {
	return []string{"ALTER TABLE " + d.Quote(table) + " DROP CONSTRAINT " + d.Quote(ck.Name)}
}
