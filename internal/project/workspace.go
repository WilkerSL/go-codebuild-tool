const WorkFile = "go.work"

var monolithMarkers = []string{"cmd/api/main.go", SnapshotFile, "internal/app/routes_gen.go"}

var workspaceMarkers = []string{contract.ContractRegistry, gen.GatewayDir + "/internal/app/routes_gen.go"}

func (p *planner) checkLayout(context.Context) error {
	if p.model.Workspace() {
		for _, marker := range monolithMarkers {
			if exists(filepath.Join(p.root, filepath.FromSlash(marker))) {
				names := make([]string, len(p.model.Services))
				for i, s := range p.model.Services {
					names[i] = s.TypeName
				}
				e := newError(KindConfig, "layout_change", fmt.Sprintf(
					"the specs declare microservices (%s), but %s holds a monolith generated by codebuild (%s). codebuild does not convert a monolith into a workspace: "+
						"create the workspace in a new directory with codebuild build --starter --module <path>, copy specs/ there and move the code of your service.go files "+
						"into services/<service>/internal/<domain>/service.go.", strings.Join(names, ", "), p.root, marker))
				e.Details = map[string]string{"found": marker}
				return e
			}
		}
		return nil
	}
	for _, marker := range workspaceMarkers {
		if exists(filepath.Join(p.root, filepath.FromSlash(marker))) {
			e := newError(KindConfig, "layout_change", fmt.Sprintf(
				"%s holds a microservice workspace (%s), but no spec declares a <Name>Service struct. Keep every entity inside its service struct; "+
					"codebuild does not convert a workspace back into a monolith.", p.root, marker))
			e.Details = map[string]string{"found": marker}
			return e
		}
	}
	return nil
}

// workspaceRoot handles commands run inside one module of a workspace, such as
// services/billing: when a parent directory holds codebuild.json and a go.work that uses
// the module, the parent is the project.
func workspaceRoot(module string) string {
	if exists(filepath.Join(module, ConfigFile)) {
		return module
	}
	dir, ok := findUp(filepath.Dir(module), ConfigFile)
	if !ok || !exists(filepath.Join(dir, WorkFile)) || !exists(filepath.Join(dir, "go.mod")) {
		return module
	}
	data, err := os.ReadFile(filepath.Join(dir, WorkFile))
	if err != nil {
		return module
	}
	work, err := modfile.ParseWork(WorkFile, data, nil)
	if err != nil {
		return module
	}
	target, err := resolveExisting(module)
	if err != nil {
		return module
	}
	for _, u := range work.Use {
		use := filepath.FromSlash(u.Path)
		if !filepath.IsAbs(use) {
			use = filepath.Join(dir, use)
		}
		if real, err := resolveExisting(use); err == nil && real == target {
			return dir
		}
	}
	return module
}

func databaseDir(name string) string {
	if name == schema.SharedDatabase {
		return gen.SharedDir + "/" + MigrationsDir
	}
	return "services/" + name + "/" + MigrationsDir
}

func migrateDir(database string) string {
	return path.Dir(databaseDir(database))
}

func (p *planner) planDatabases() error {
	dbs := schema.BuildDatabases(p.model)
	names := make([]string, 0, len(dbs))
	for name := range dbs {
		names = append(names, name)
	}
	slices.Sort(names)
	p.databases = map[string]bool{}
	for _, name := range names {
		info, hasSQL, err := p.planDatabase(databaseDir(name), dbs[name])
		if err != nil {
			return err
		}
		if info != nil {
			info.Database = name
			p.plan.Migrations = append(p.plan.Migrations, *info)
		}
		p.databases[name] = hasSQL || info != nil
	}
	return nil
}

func (p *planner) generateWorkspace() error {
	registry := contract.NewRegistry()
	data, err := os.ReadFile(filepath.Join(p.root, filepath.FromSlash(contract.ContractRegistry)))
	switch {
	case err == nil:
		if registry, err = contract.UnmarshalRegistry(data); err != nil {
			return newError(KindConfig, "invalid_contracts", fmt.Sprintf("%s: %v", contract.ContractRegistry, err))
		}
	case !errors.Is(err, fs.ErrNotExist):
		return newError(KindInternal, "read_contracts", err.Error())
	}
	set := contract.Build(p.plan.Module, p.model, registry)
	for _, change := range registry.Renumbered {
		p.plan.Warnings = append(p.plan.Warnings, "contracts: "+change+"; old clients ignore the field until they are rebuilt, so deploy the services before the gateway")
	}
	ws, err := gen.GenerateWorkspace(gen.WorkspaceOptions{
		Module:     p.plan.Module,
		GoVersion:  p.plan.Target.GoVersion,
		Caps:       p.plan.Target.Caps,
		Dialect:    p.dialect,
		Model:      p.model,
		Pagination: p.cfg.Pagination,
		Contracts:  set,
		Migrations: p.databases,
		Parts:      p.cfg.Generate,
	})
	if err != nil {
		return newError(KindInternal, "generate", err.Error())
	}
	p.addGenerated(ws.Files)
	state, err := set.Registry().Marshal()
	if err != nil {
		return newError(KindInternal, "contracts", err.Error())
	}
	p.add(contract.ContractRegistry, state, OwnerState)
	p.modules = ws.Modules
	entries, _ := os.ReadDir(filepath.Join(p.root, "services"))
	for _, entry := range entries {
		if entry.IsDir() && p.model.Service(entry.Name()) == nil {
			p.plan.Warnings = append(p.plan.Warnings, fmt.Sprintf(
				"services/%s no longer matches a service in specs/: after codebuild build --prune, delete the directory, its use line in %s and .github/workflows/services-%s.yml", entry.Name(), WorkFile, entry.Name()))
		}
	}
	if len(p.cfg.ManualWiring) > 0 {
		p.plan.Warnings = append(p.plan.Warnings, "manualWiring in "+ConfigFile+" is ignored in a microservice workspace: the gateway wires every route")
	}
	return nil
}

func relativeDir(from, to string) string {
	rel, err := filepath.Rel(filepath.FromSlash(from), filepath.FromSlash(to))
	if err != nil {
		return to
	}
	rel = filepath.ToSlash(rel)
	if !strings.HasPrefix(rel, ".") {
		rel = "./" + rel
	}
	return rel
}

// planModuleFile creates or completes the go.mod of one module. Local modules get a
// replace directive, so the module also builds alone with GOWORK=off, which is how its
// Dockerfile and its CI workflow build it.
func (p *planner) planModuleFile(m gen.Module) error {
	file := m.Dir + "/go.mod"
	data, err := os.ReadFile(filepath.Join(p.root, filepath.FromSlash(file)))
	created := errors.Is(err, fs.ErrNotExist)
	switch {
	case created:
		data = []byte(fmt.Sprintf("module %s\n\ngo %s\n", m.Path, p.plan.Target.GoVersion))
	case err != nil:
		return newError(KindInternal, "read_go_mod", err.Error())
	}
	f, err := modfile.Parse(file, data, nil)
	if err != nil {
		return newError(KindConfig, "invalid_go_mod", err.Error())
	}
	if f.Module != nil && f.Module.Mod.Path != m.Path {
		p.plan.Warnings = append(p.plan.Warnings, fmt.Sprintf("%s declares module %s, but the workspace expects %s; the generated imports use %s", file, f.Module.Mod.Path, m.Path, m.Path))
	}
	modified := created
	if up := p.plan.GoUpgrade; up != nil && !created {
		if err := f.AddGoStmt(up.To); err != nil {
			return newError(KindInternal, "go_mod", err.Error())
		}
		modified = true
	}
	requires := slices.Clone(m.Requires)
	for _, local := range m.Locals {
		requires = append(requires, [2]string{p.plan.Module + "/" + local, "v0.0.0"})
	}
	slices.SortFunc(requires, func(a, b [2]string) int { return strings.Compare(a[0], b[0]) })
	for _, r := range requires {
		if !slices.ContainsFunc(f.Require, func(req *modfile.Require) bool { return req.Mod.Path == r[0] }) {
			f.AddNewRequire(r[0], r[1], false)
			modified = true
		}
	}
	for _, local := range m.Locals {
		modPath := p.plan.Module + "/" + local
		if slices.ContainsFunc(f.Replace, func(r *modfile.Replace) bool { return r.Old.Path == modPath }) {
			continue
		}
		if err := f.AddReplace(modPath, "", relativeDir(m.Dir, local), ""); err != nil {
			return newError(KindInternal, "go_mod", err.Error())
		}
		modified = true
	}
	if modified {
		f.Cleanup()
		data = modfile.Format(f.Syntax)
	}
	p.add(file, data, OwnerGoMod)
	return nil
}

func (p *planner) planWorkFile() error {
	data, err := os.ReadFile(filepath.Join(p.root, WorkFile))
	created := errors.Is(err, fs.ErrNotExist)
	switch {
	case created:
		data = []byte(fmt.Sprintf("go %s\n", p.plan.Target.GoVersion))
	case err != nil:
		return newError(KindInternal, "read_go_work", err.Error())
	}
	f, err := modfile.ParseWork(WorkFile, data, nil)
	if err != nil {
		return newError(KindConfig, "invalid_go_work", err.Error())
	}
	modified := created
	if up := p.plan.GoUpgrade; up != nil && !created {
		if err := f.AddGoStmt(up.To); err != nil {
			return newError(KindInternal, "go_work", err.Error())
		}
		modified = true
	}
	used := map[string]bool{}
	for _, u := range f.Use {
		used[path.Clean(filepath.ToSlash(u.Path))] = true
	}
	dirs := []string{"."}
	for _, m := range p.modules {
		dirs = append(dirs, m.Dir)
	}
	for _, dir := range dirs {
		if used[path.Clean(dir)] {
			continue
		}
		use := dir
		if dir != "." {
			use = "./" + dir
		}
		if err := f.AddUse(use, ""); err != nil {
			return newError(KindInternal, "go_work", err.Error())
		}
		modified = true
	}
	if modified {
		f.Cleanup()
		data = modfile.Format(f.Syntax)
	}
	p.add(WorkFile, data, OwnerGoMod)
	return nil
}

func (p *planner) planWorkspaceMods() error {
	data := p.modData
	if p.opts.Starter {
		data = []byte(fmt.Sprintf("module %s\n\ngo %s\n", p.plan.Module, p.plan.Target.GoVersion))
	} else if up := p.plan.GoUpgrade; up != nil {
		f, err := modfile.Parse("go.mod", data, nil)
		if err != nil {
			return newError(KindConfig, "invalid_go_mod", err.Error())
		}
		if err := f.AddGoStmt(up.To); err != nil {
			return newError(KindInternal, "go_mod", err.Error())
		}
		f.Cleanup()
		data = modfile.Format(f.Syntax)
	}
	p.add("go.mod", data, OwnerGoMod)
	for _, m := range p.modules {
		if err := p.planModuleFile(m); err != nil {
			return err
		}
	}
	return p.planWorkFile()
}

func (p *planner) workspaceSteps(changed map[string]Action) []string {
	var steps []string
	for _, m := range p.modules {
		if a := changed[m.Dir+"/go.mod"]; a == ActionCreate || a == ActionUpdate {
			steps = append(steps, "go -C "+m.Dir+" mod tidy")
		}
	}
	if p.plan.HasChanges() {
		// Inside a workspace ./... stops at nested modules; the module path pattern
		// covers all of them.
		all := p.plan.Module + "/..."
		steps = append(steps, "go build "+all+" && go vet "+all+" && go test "+all)
	}
	for _, mi := range p.plan.Migrations {
		steps = append(steps, fmt.Sprintf("go run ./%s/cmd/migrate up (with DATABASE_URL of the %s database)", migrateDir(mi.Database), mi.Database))
	}
	mains := []string{"gateway/cmd/gateway/main.go"}
	for _, m := range p.modules {
		mains = append(mains, m.Dir+"/cmd/server/main.go")
	}
	p.telemetryWarning(mains...)
	if p.opts.Starter {
		if !exists(filepath.Join(p.root, "certs")) {
			steps = append(steps, "go run ./gateway/cmd/devcerts (development certificates for running the services without docker compose)")
		}
		steps = append(steps, "docker compose up --build")
		steps = append(steps, "go get -tool github.com/WilkerSL/go-codebuild-tool/cmd/codebuild (optional, pins codebuild for go tool codebuild)")
	}
	return steps
}
