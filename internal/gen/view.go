func goBase(k schema.Kind) string {
	return k.GoType()
}

func goType(f *schema.Field) string {
	if f.Nullable {
		return "*" + goBase(f.Kind)
	}
	return goBase(f.Kind)
}

func nonNull(f *schema.Field) *schema.Field {
	c := *f
	c.Nullable = false
	return &c
}

func argExpr(f *schema.Field, expr string) string {
	switch {
	case f.Kind == schema.KindUUID && f.Nullable:
		return "database.NullUUIDArg(" + expr + ")"
	case f.Kind == schema.KindUUID:
		return "database.UUIDArg(" + expr + ")"
	case f.Kind == schema.KindTime && f.Nullable:
		return "database.NullTimeArg(" + expr + ")"
	case f.Kind == schema.KindTime:
		return "database.TimeArg(" + expr + ")"
	case f.Kind == schema.KindBytes && !f.Nullable:
		return "database.BytesArg(" + expr + ")"
	}
	return expr
}

func filterArg(f *schema.Field) string {
	if f.Kind == schema.KindUUID {
		return "database.NullUUIDArg(p." + f.Name + ")"
	}
	return "p." + f.Name
}

func queryArgs(q dialect.Query, sourceVar string) string {
	var out []string
	for _, a := range q.Args {
		switch a.Kind {
		case dialect.ArgID:
			out = append(out, argExpr(nonNull(a.Field), "id"))
		case dialect.ArgInput:
			out = append(out, argExpr(a.Field, "in."+a.Field.Name))
		case dialect.ArgFilter:
			out = append(out, filterArg(a.Field))
		case dialect.ArgLimit:
			out = append(out, "p.Limit")
		case dialect.ArgOffset:
			out = append(out, "p.Offset")
		case dialect.ArgSourceID:
			out = append(out, argExpr(nonNull(a.Field), sourceVar))
		case dialect.ArgOwner:
			out = append(out, argExpr(nonNull(a.Field), "ownerID"))
		case dialect.ArgPassword:
			out = append(out, "passwordHash")
		}
	}
	return strings.Join(out, ", ")
}

func pathParse(f *schema.Field, name string) string {
	switch {
	case f.Kind == schema.KindUUID:
		return `httpx.PathUUID(r, "` + name + `")`
	case f.Kind.IsInteger():
		return `httpx.PathInt[` + goBase(f.Kind) + `](r, "` + name + `")`
	}
	return `httpx.PathString(r, "` + name + `")`
}

func idString(f *schema.Field, expr string) string {
	switch {
	case f.Kind == schema.KindUUID:
		return expr + ".String()"
	case f.Kind.IsInteger():
		return "strconv.FormatInt(int64(" + expr + "), 10)"
	}
	return "url.PathEscape(" + expr + ")"
}

func requestType(f *schema.Field) string {
	switch f.Kind {
	case schema.KindUUID, schema.KindTime:
		return "*string"
	}
	return "*" + goBase(f.Kind)
}

func enumConstName(f *schema.Field, item string) string {
	return f.Name + naming.Pascal(item)
}

func defaultLiteral(f *schema.Field) string {
	if f.Kind == schema.KindString {
		if slices.Contains(f.Enum, f.Default) {
			return enumConstName(f, f.Default)
		}
		return strconv.Quote(f.Default)
	}
	return f.Default
}

func convertBlock(f *schema.Field) string {
	req := "req." + f.InputName()
	in := "in." + f.InputName()
	j := strconv.Quote(f.InputJSON())
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	switch f.Kind {
	case schema.KindUUID, schema.KindTime:
		parse, message := "uuid.Parse(*"+req+")", "must be a valid UUID"
		if f.Kind == schema.KindTime {
			parse, message = "time.Parse(time.RFC3339Nano, *"+req+")", "must be an RFC 3339 timestamp"
		}
		assign := in + " = v"
		if f.Nullable {
			assign = in + " = &v"
		}
		if f.Required {
			w("if %s == nil {\nerrs.Add(%s, \"is required\")\n} else if v, err := %s; err != nil {\nerrs.Add(%s, %q)\n} else {\n%s\n}\n", req, j, parse, j, message, assign)
		} else {
			w("if %s != nil {\nif v, err := %s; err != nil {\nerrs.Add(%s, %q)\n} else {\n%s\n}\n}\n", req, parse, j, message, assign)
		}
	default:
		switch {
		case f.Required && f.Identity && f.Email:
			w("if %s == nil {\nerrs.Add(%s, \"is required\")\n} else {\n%s = strings.ToLower(*%s)\n}\n", req, j, in, req)
		case f.Required:
			w("if %s == nil {\nerrs.Add(%s, \"is required\")\n} else {\n%s = *%s\n}\n", req, j, in, req)
		case f.Nullable && f.HasDefault:
			w("%s = %s\nif %s == nil {\n%s = new(%s(%s))\n}\n", in, req, in, in, goBase(f.Kind), defaultLiteral(f))
		case f.Nullable:
			w("%s = %s\n", in, req)
		case f.HasDefault:
			w("%s = %s\nif %s != nil {\n%s = *%s\n}\n", in, defaultLiteral(f), req, in, req)
		case f.Kind == schema.KindBytes:
			w("%s = []byte{}\nif %s != nil {\n%s = *%s\n}\n", in, req, in, req)
		default:
			w("if %s != nil {\n%s = *%s\n}\n", req, in, req)
		}
	}
	return b.String()
}

func updateBlock(f *schema.Field) string {
	c := *f
	c.Required = !f.Nullable
	return convertBlock(&c)
}

func hasRules(f *schema.Field) bool {
	return f.NotEmpty || f.Min != "" || f.Max != "" || f.Email || len(f.Enum) > 0
}

const maxPasswordLength = 1024

func fieldMax(f *schema.Field) string {
	if f.Password {
		return strconv.Itoa(maxPasswordLength)
	}
	return f.Max
}

func enumList(f *schema.Field) (string, string) {
	consts := make([]string, len(f.Enum))
	for i, item := range f.Enum {
		consts[i] = enumConstName(f, item)
	}
	return strings.Join(consts, ", "), strings.Join(f.Enum, ", ")
}

func checkBody(f *schema.Field) string {
	j := strconv.Quote(f.InputJSON())
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	switch {
	case f.Kind == schema.KindString:
		if f.NotEmpty {
			w("if strings.TrimSpace(v) == \"\" {\nerrs.Add(%s, \"must not be empty\")\n}\n", j)
		}
		if limit := fieldMax(f); f.Min != "" || limit != "" {
			w("n := utf8.RuneCountInString(v)\n")
			if f.Min != "" {
				w("if n < %s {\nerrs.Add(%s, \"must be at least %s characters\")\n}\n", f.Min, j, f.Min)
			}
			if limit != "" {
				w("if n > %s {\nerrs.Add(%s, \"must be at most %s characters\")\n}\n", limit, j, limit)
			}
		}
		if f.Email {
			w("if !validation.Email(v) {\nerrs.Add(%s, \"must be a valid email address\")\n}\n", j)
		}
		if len(f.Enum) > 0 {
			consts, items := enumList(f)
			w("switch v {\ncase %s:\ndefault:\nerrs.Add(%s, %q)\n}\n", consts, j, "must be one of: "+items)
		}
	case f.Kind == schema.KindBytes:
		if f.NotEmpty {
			w("if len(v) == 0 {\nerrs.Add(%s, \"must not be empty\")\n}\n", j)
		}
		if f.Min != "" {
			w("if len(v) < %s {\nerrs.Add(%s, \"must be at least %s bytes\")\n}\n", f.Min, j, f.Min)
		}
		if f.Max != "" {
			w("if len(v) > %s {\nerrs.Add(%s, \"must be at most %s bytes\")\n}\n", f.Max, j, f.Max)
		}
	case f.Kind.IsNumeric():
		if f.Min != "" {
			w("if v < %s {\nerrs.Add(%s, \"must be at least %s\")\n}\n", f.Min, j, f.Min)
		}
		if f.Max != "" {
			w("if v > %s {\nerrs.Add(%s, \"must be at most %s\")\n}\n", f.Max, j, f.Max)
		}
	}
	return b.String()
}

func validateCall(f *schema.Field) string {
	in := f.InputName()
	if f.Nullable {
		return fmt.Sprintf("if in.%s != nil {\ncheck%s(&errs, *in.%s)\n}", in, f.Name, in)
	}
	return fmt.Sprintf("check%s(&errs, in.%s)", f.Name, in)
}

func filterParse(f *schema.Field) string {
	j := strconv.Quote(f.JSON)
	switch {
	case f.Kind == schema.KindUUID:
		return fmt.Sprintf("p.%s = httpx.QueryUUID(q, %s, &errs)", f.Name, j)
	case f.Kind == schema.KindBool:
		return fmt.Sprintf("p.%s = httpx.QueryBool(q, %s, &errs)", f.Name, j)
	case f.Kind.IsInteger():
		return fmt.Sprintf("p.%s = httpx.QueryInt[%s](q, %s, &errs)", f.Name, goBase(f.Kind), j)
	}
	line := fmt.Sprintf("p.%s = httpx.QueryString(q, %s)", f.Name, j)
	if len(f.Enum) > 0 {
		consts, items := enumList(f)
		line += fmt.Sprintf("\nif p.%s != nil {\nswitch *p.%s {\ncase %s:\ndefault:\nerrs.Add(%s, %q)\n}\n}", f.Name, f.Name, consts, j, "must be one of: "+items)
	}
	return line
}

func scanTarget(f *schema.Field, scanTime bool) string {
	ref := "&item." + f.Name
	switch {
	case f.Kind == schema.KindUUID && f.Nullable:
		return "database.ScanNullUUID(" + ref + ")"
	case f.Kind == schema.KindUUID:
		return "database.ScanUUID(" + ref + ")"
	case f.Kind == schema.KindTime && scanTime && f.Nullable:
		return "database.ScanNullTime(" + ref + ")"
	case f.Kind == schema.KindTime && scanTime:
		return "database.ScanTime(" + ref + ")"
	}
	return ref
}

func intBounds(f *schema.Field) (int64, int64, bool, bool) {
	var lo, hi int64
	hasLo, hasHi := f.Min != "", f.Max != ""
	if hasLo {
		lo, _ = strconv.ParseInt(f.Min, 10, 64)
	}
	if hasHi {
		hi, _ = strconv.ParseInt(f.Max, 10, 64)
	}
	return lo, hi, hasLo, hasHi
}

func floatBounds(f *schema.Field) (float64, float64, bool, bool) {
	var lo, hi float64
	hasLo, hasHi := f.Min != "", f.Max != ""
	if hasLo {
		lo, _ = strconv.ParseFloat(f.Min, 64)
	}
	if hasHi {
		hi, _ = strconv.ParseFloat(f.Max, 64)
	}
	return lo, hi, hasLo, hasHi
}

func stringLength(f *schema.Field) int {
	n := 1
	if f.Min != "" {
		n, _ = strconv.Atoi(f.Min)
		n = max(n, 1)
	}
	if f.Max != "" {
		limit, _ := strconv.Atoi(f.Max)
		n = min(n, limit)
	}
	return n
}

func uniqueLength(f *schema.Field) int {
	n := 16
	if f.Min != "" {
		lo, _ := strconv.Atoi(f.Min)
		n = max(n, lo)
	}
	if f.Max != "" {
		hi, _ := strconv.Atoi(f.Max)
		n = min(n, hi)
	}
	return n
}

func validValue(f *schema.Field, qualifier string, unique bool) string {
	switch f.Kind {
	case schema.KindString:
		switch {
		case len(f.Enum) > 0:
			return qualifier + enumConstName(f, f.Enum[0])
		case f.Email:
			limit := 254
			if f.Max != "" {
				limit, _ = strconv.Atoi(f.Max)
			}
			return fmt.Sprintf("fixtureEmail(%d)", limit)
		case unique:
			return fmt.Sprintf("fixtureString(%d)", uniqueLength(f))
		}
		return strconv.Quote(strings.Repeat("a", stringLength(f)))
	case schema.KindBytes:
		return "[]byte(" + strconv.Quote(strings.Repeat("a", stringLength(f))) + ")"
	case schema.KindBool:
		return "true"
	case schema.KindTime:
		return "time.Date(2024, time.January, 2, 3, 4, 5, 0, time.UTC)"
	case schema.KindUUID:
		return "uuid.New()"
	case schema.KindFloat32, schema.KindFloat64:
		lo, hi, hasLo, hasHi := floatBounds(f)
		v := 1.5
		if hasLo {
			v = lo
		}
		if hasHi && v > hi {
			v = hi
		}
		return strconv.FormatFloat(v, 'g', -1, 64)
	default:
		lo, hi, hasLo, hasHi := intBounds(f)
		if unique {
			if !hasLo {
				lo = 1
			}
			if !hasHi {
				hi = 1 << 30
			}
			return fmt.Sprintf("fixtureInt[%s](%d, %d)", goBase(f.Kind), lo, hi)
		}
		v := int64(1)
		if hasLo {
			v = lo
		}
		if hasHi && v > hi {
			v = hi
		}
		return strconv.FormatInt(v, 10)
	}
}

func wrapNullable(f *schema.Field, value string) string {
	if f.Nullable {
		return "new(" + goBase(f.Kind) + "(" + value + "))"
	}
	return value
}

func failingCases(f *schema.Field) []failingCase {
	var cases []failingCase
	add := func(rule, value string) {
		cases = append(cases, failingCase{Rule: rule, Assign: wrapNullable(f, value)})
	}
	switch {
	case f.Kind == schema.KindString:
		if f.NotEmpty {
			add("notempty", `"   "`)
		}
		if f.Min != "" {
			if n, _ := strconv.Atoi(f.Min); n > 0 {
				add("min", strconv.Quote(strings.Repeat("a", n-1)))
			}
		}
		if limit := fieldMax(f); limit != "" {
			n, _ := strconv.Atoi(limit)
			add("max", fmt.Sprintf("strings.Repeat(%q, %d)", "a", n+1))
		}
		if f.Email {
			add("email", `"not an email"`)
		}
		if len(f.Enum) > 0 {
			add("enum", `"zz-not-allowed"`)
		}
	case f.Kind == schema.KindBytes:
		if f.NotEmpty {
			add("notempty", "[]byte{}")
		}
		if f.Min != "" {
			if n, _ := strconv.Atoi(f.Min); n > 0 {
				add("min", fmt.Sprintf("make([]byte, %d)", n-1))
			}
		}
		if f.Max != "" {
			n, _ := strconv.Atoi(f.Max)
			add("max", fmt.Sprintf("make([]byte, %d)", n+1))
		}
	case f.Kind.IsInteger():
		lo, hi, hasLo, hasHi := intBounds(f)
		if hasLo && lo > minInt(f.Kind) {
			add("min", strconv.FormatInt(lo-1, 10))
		}
		if hasHi && hi < maxInt(f.Kind) {
			add("max", strconv.FormatInt(hi+1, 10))
		}
	case f.Kind.IsFloat():
		lo, hi, hasLo, hasHi := floatBounds(f)
		if hasLo {
			add("min", strconv.FormatFloat(lo-1, 'g', -1, 64))
		}
		if hasHi {
			add("max", strconv.FormatFloat(hi+1, 'g', -1, 64))
		}
	}
	return cases
}

func minInt(k schema.Kind) int64 {
	switch k {
	case schema.KindInt16:
		return -1 << 15
	case schema.KindInt32:
		return -1 << 31
	}
	return -1 << 63
}

func maxInt(k schema.Kind) int64 {
	switch k {
	case schema.KindInt16:
		return 1<<15 - 1
	case schema.KindInt32:
		return 1<<31 - 1
	}
	return 1<<63 - 1
}

func newFieldView(f *schema.Field, dv dialectView) *fieldView {
	v := &fieldView{
		F:             f,
		Name:          f.Name,
		JSON:          f.JSON,
		Input:         f.InputName(),
		InputJSON:     f.InputJSON(),
		GoType:        goType(f),
		BaseType:      goBase(f.Kind),
		RequestType:   requestType(f),
		ScanTarget:    scanTarget(f, dv.ScanTime),
		Convert:       convertBlock(f),
		UpdateConvert: updateBlock(f),
		HasRules:      hasRules(f),
		CheckFunc:     "check" + f.Name,
		CheckBody:     checkBody(f),
		FilterType:    "*" + goBase(f.Kind),
		FilterParse:   filterParse(f),
	}
	v.ModelTag = "`json:\"" + f.JSON + "\"`"
	if f.OmitResponse {
		v.ModelTag = "`json:\"-\"`"
	}
	for _, item := range f.Enum {
		v.EnumConsts = append(v.EnumConsts, enumConst{Name: enumConstName(f, item), Value: strconv.Quote(item)})
	}
	v.ValidValue = validValue(f, "", f.Unique || f.PK)
	v.FailingCases = failingCases(f)
	return v
}
