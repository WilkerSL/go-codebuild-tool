func goStringLiteral(sql string) string {
	if !strings.Contains(sql, "`") {
		return "`\n" + sql + "`"
	}
	lines := strings.Split(sql, "\n")
	parts := make([]string, len(lines))
	for i, line := range lines {
		if i < len(lines)-1 {
			line += "\n"
		}
		parts[i] = strconv.Quote(line)
	}
	return strings.Join(parts, " +\n\t")
}

